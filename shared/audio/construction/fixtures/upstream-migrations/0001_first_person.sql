CREATE TABLE IF NOT EXISTS fp_rooms (
 code TEXT PRIMARY KEY NOT NULL,
 host TEXT NOT NULL,
 world TEXT NOT NULL,
 version INTEGER NOT NULL DEFAULT 0,
 updated INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS fp_players (
 id TEXT PRIMARY KEY NOT NULL,
 room TEXT NOT NULL REFERENCES fp_rooms(code) ON DELETE CASCADE,
 token_hash TEXT NOT NULL,
 name TEXT NOT NULL,
 color INTEGER NOT NULL,
 slot INTEGER NOT NULL,
 x REAL NOT NULL, y REAL NOT NULL, z REAL NOT NULL,
 yaw REAL NOT NULL, pitch REAL NOT NULL,
 seen INTEGER NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS fp_players_room_slot ON fp_players(room, slot);
