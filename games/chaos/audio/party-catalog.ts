const clean =
  ' Close dry Foley, playful physical timing, clear short decay. No speech, music, harsh alarm or cinematic boom.';
function effect(
  id: string,
  name: string,
  group: string,
  source: string,
  trigger: string,
  duration = 1.5,
  volume = 0.8,
  loop = false,
): Cue {
  return {
    id,
    name,
    group,
    prompt: source + clean,
    trigger,
    duration,
    volume,
    loop,
    text: '',
    category: loop ? 'ambience' : 'event',
    priority: 'core',
  };
}
function line(
  id: string,
  name: string,
  text: string,
  trigger: string,
  group = 'Crew voices',
  prompt = '[playfully]',
): Cue {
  return {
    id: 'speech.' + id,
    name,
    group,
    prompt,
    text,
    trigger,
    duration: 5,
    volume: 0.85,
    loop: false,
    category: 'speech',
    priority: 'detail',
  };
}
