/** Existing physical cues get separately generated takes without changing saved defaults. */
export function variations(cues: Cue[]): Cue[] {
  const ids = [
    'step.concrete',
    'step.dirt',
    'event.bonk',
    'material.sofa.impact',
    'material.wood.place',
    'material.wall.place',
    'material.duck.impact',
    'prop.duck.use',
    'party.handle',
    'party.glass.crack',
    'party.barrow.spill',
  ];
  return cues
    .filter((c) => ids.includes(c.id))
    .flatMap((c) =>
      [1, 2].map((n) => ({
        ...c,
        id: `${c.id}.alt${n}`,
        name: `${c.name} · Take ${n + 1}`,
        variantOf: c.id,
        priority: 'variation' as const,
        prompt: `${c.prompt.replace(clean, '').slice(0, 315)} ${n === 1 ? 'A separate take with a slightly softer attack and lower natural resonance.' : 'A separate take with a quicker contact and slightly brighter natural resonance.'} No music or speech.`,
        trigger: `Alternates with ${c.name}; avoids repeating the same take back to back.`,
      })),
    );
}
