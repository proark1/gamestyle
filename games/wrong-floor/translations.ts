export type HotelText = keyof typeof german;
export function hotelText(text: HotelText, language: string) {
  return language === 'de' ? german[text] : text;
}
export function hotelError(message: string, language: string) {
  if (language !== 'de') return message;
  return (
    german[message as HotelText] ??
    german[
      'Something went wrong. Check the room code or reconnect and try again.'
    ]
  );
}
